export function getAgenciesForWilaya(wilaya) {
  if (!wilaya) return [];
  const codeMatch = String(wilaya).match(/^(\d{2})/);
  const code = codeMatch ? codeMatch[1] : '16';
  return YALIDINE_AGENCIES[code] || [
    { id: Number(code) * 1000 + 101, name: `وكالة ياليدين المركزية - ولاية ${wilaya}`, commune: "Centre" }
  ];
}
